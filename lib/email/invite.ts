import { APP_NAME, COMPANY_NAME, isSupabaseConfigured } from '../config';
import { ROLE_LABEL } from '../domain/permissions';
import type { Role } from '../domain/types';
import { ValidationError } from '../data/errors';
import { isServiceRoleConfigured, supabaseAdmin } from '../supabase/admin';
import { appUrl, escapeHtml, type EmailMessage } from './templates';
import { sendEmail } from './send';

/**
 * Invite delivery (ADM-01). With Supabase configured the invite is a magic link from Supabase Auth
 * (`auth.admin.inviteUserByEmail`, service role, server-only); a re-send to someone who already has
 * an auth account uses a magic link generated by `auth.admin.generateLink` and sent by us. Without
 * Supabase (demo and local Postgres) we send a plain invite email, which lands in the dev outbox
 * (/api/dev/outbox) when RESEND_API_KEY is not set.
 */
export interface InviteDeliveryInput {
  email: string;
  role: Role;
  orgName: string;
  workspaceName: string;
  resend?: boolean;
}

export interface InviteDeliveryResult {
  channel: 'supabase' | 'email';
  /** The Supabase auth user created by the invite, when there is one. */
  authUserId: string | null;
}

export function inviteEmail(
  i: Pick<InviteDeliveryInput, 'email' | 'role' | 'orgName' | 'workspaceName'>,
  href: string,
): EmailMessage {
  const subject = `You're invited to ${i.workspaceName}`;
  const role = ROLE_LABEL[i.role];
  return {
    to: i.email,
    subject,
    html:
      `<!doctype html><html lang="en"><body style="font-family:Inter,Segoe UI,Arial,sans-serif;color:#0F172A">` +
      `<h1 style="font-size:20px">${escapeHtml(subject)}</h1>` +
      `<p>You have been invited to join <strong>${escapeHtml(i.orgName)}</strong> in ${escapeHtml(i.workspaceName)} ` +
      `as <strong>${escapeHtml(role)}</strong>.</p>` +
      `<p><a href="${escapeHtml(href)}" style="display:inline-block;background:#0F9488;color:#FFFFFF;` +
      `text-decoration:none;font-weight:700;padding:12px 20px;border-radius:10px">Accept the invite</a></p>` +
      `<p style="color:#475569;font-size:12px">Or paste this link: ${escapeHtml(href)}</p>` +
      `<p style="color:#475569;font-size:12px">${escapeHtml(COMPANY_NAME)} · ${escapeHtml(APP_NAME)}</p>` +
      `</body></html>`,
    text: `${subject}\n\nJoin ${i.orgName} as ${role}: ${href}\n`,
  };
}

export async function deliverInvite(i: InviteDeliveryInput): Promise<InviteDeliveryResult> {
  if (!isSupabaseConfigured()) {
    await sendEmail(inviteEmail(i, appUrl('/auth/sign-in')));
    return { channel: 'email', authUserId: null };
  }
  if (!isServiceRoleConfigured())
    throw new ValidationError('Set SUPABASE_SERVICE_ROLE_KEY on the server to send invites.');
  const auth = supabaseAdmin().auth.admin;
  const redirectTo = appUrl('/auth/callback');
  const { data, error } = await auth.inviteUserByEmail(i.email, {
    redirectTo,
    data: { role: i.role, org: i.orgName },
  });
  if (!error) return { channel: 'supabase', authUserId: data.user?.id ?? null };
  if (!i.resend && !/already|registered|exists/i.test(error.message))
    throw new ValidationError(`Invite failed: ${error.message}`);
  // Already has an auth account (a re-send, or an invite accepted elsewhere): send a magic link.
  const link = await auth.generateLink({ type: 'magiclink', email: i.email, options: { redirectTo } });
  if (link.error || !link.data.properties?.action_link)
    throw new ValidationError(`Invite failed: ${link.error?.message ?? error.message}`);
  await sendEmail(inviteEmail(i, link.data.properties.action_link));
  return { channel: 'supabase', authUserId: link.data.user?.id ?? null };
}

/** Deactivation also blocks sign-in at Supabase Auth (ban), when it is configured. */
export async function setAuthBan(userId: string, banned: boolean) {
  if (!isServiceRoleConfigured()) return;
  const { error } = await supabaseAdmin().auth.admin.updateUserById(userId, {
    ban_duration: banned ? '876000h' : 'none',
  });
  if (error && !/not found/i.test(error.message))
    throw new ValidationError(`Auth update failed: ${error.message}`);
}
