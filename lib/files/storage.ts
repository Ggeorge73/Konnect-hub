import 'server-only';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { isSupabaseConfigured } from '../config';
import { isPostgresEnabled } from '../data';
import { ALLOWED_TYPES, MAX_FILE_BYTES, SIGNED_URL_TTL_SECONDS, contentDisposition } from '../domain/files';
import { supabaseAdmin } from '../supabase/admin';

/**
 * Where attachment and logo bytes live (FILE-01). One interface, three backends:
 * - Supabase (production): private buckets, one per client org, created on first use; downloads
 *   are 5-minute signed URLs issued only by the authorised download route.
 * - Disk (Postgres without Supabase): files under the OS temp dir.
 * - Memory (demo mode): a process-wide map.
 * Bucket names and paths are always generated by the server, never taken from a request.
 */
export interface StoredFile {
  bytes: Uint8Array;
  contentType: string;
}

export interface FileStorage {
  kind: 'supabase' | 'disk' | 'memory';
  put(bucket: string, key: string, bytes: Uint8Array, contentType: string): Promise<void>;
  /** The bytes (disk and memory backends; Supabase serves signed URLs instead). */
  read(bucket: string, key: string): Promise<StoredFile | null>;
  /** A short-lived download URL (Supabase only); null for the local backends. */
  signedUrl(bucket: string, key: string, downloadName: string, ttlSeconds?: number): Promise<string | null>;
  remove(bucket: string, key: string): Promise<void>;
}

const SAFE_BUCKET = /^[a-z0-9][a-z0-9.-]{1,62}$/;
const checkLocation = (bucket: string, key: string) => {
  if (
    !SAFE_BUCKET.test(bucket) ||
    !key ||
    key.startsWith('/') ||
    key.split('/').some((p) => p === '..' || !p)
  )
    throw new Error('Invalid storage location');
};

// ---------------------------------------------------------------------------
// Memory (demo mode)
// ---------------------------------------------------------------------------
const g = globalThis as unknown as { __khFiles?: Map<string, StoredFile> };
const files = () => (g.__khFiles ??= new Map());

export const memoryStorage: FileStorage = {
  kind: 'memory',
  async put(bucket, key, bytes, contentType) {
    checkLocation(bucket, key);
    files().set(`${bucket}/${key}`, { bytes: new Uint8Array(bytes), contentType });
  },
  async read(bucket, key) {
    checkLocation(bucket, key);
    return files().get(`${bucket}/${key}`) ?? null;
  },
  async signedUrl() {
    return null;
  },
  async remove(bucket, key) {
    checkLocation(bucket, key);
    files().delete(`${bucket}/${key}`);
  },
};

// ---------------------------------------------------------------------------
// Disk (Postgres mode without Supabase)
// ---------------------------------------------------------------------------
export function diskStorage(root = path.join(tmpdir(), 'konnect-hub-files')): FileStorage {
  const resolve = (bucket: string, key: string) => {
    checkLocation(bucket, key);
    const p = path.resolve(root, bucket, key);
    if (!p.startsWith(path.resolve(root) + path.sep)) throw new Error('Invalid storage location');
    return p;
  };
  return {
    kind: 'disk',
    async put(bucket, key, bytes, contentType) {
      const p = resolve(bucket, key);
      await mkdir(path.dirname(p), { recursive: true });
      await writeFile(p, bytes);
      await writeFile(`${p}.type`, contentType);
    },
    async read(bucket, key) {
      const p = resolve(bucket, key);
      try {
        const [bytes, type] = await Promise.all([readFile(p), readFile(`${p}.type`, 'utf8')]);
        return { bytes: new Uint8Array(bytes), contentType: type };
      } catch {
        return null;
      }
    },
    async signedUrl() {
      return null;
    },
    async remove(bucket, key) {
      const p = resolve(bucket, key);
      await rm(p, { force: true });
      await rm(`${p}.type`, { force: true });
    },
  };
}

// ---------------------------------------------------------------------------
// Supabase Storage (production)
// ---------------------------------------------------------------------------
const ensured = new Set<string>();

async function ensureBucket(bucket: string) {
  if (ensured.has(bucket)) return;
  const storage = supabaseAdmin().storage;
  const { data } = await storage.getBucket(bucket);
  if (!data) {
    const { error } = await storage.createBucket(bucket, {
      public: false,
      fileSizeLimit: MAX_FILE_BYTES,
      allowedMimeTypes: Object.keys(ALLOWED_TYPES),
    });
    if (error && !/already exists/i.test(error.message)) throw new Error(`Storage: ${error.message}`);
  }
  ensured.add(bucket);
}

export const supabaseStorage: FileStorage = {
  kind: 'supabase',
  async put(bucket, key, bytes, contentType) {
    checkLocation(bucket, key);
    await ensureBucket(bucket);
    const { error } = await supabaseAdmin()
      .storage.from(bucket)
      .upload(key, bytes, { contentType, upsert: true, cacheControl: 'private, max-age=0' });
    if (error) throw new Error(`Storage upload failed: ${error.message}`);
  },
  async read(bucket, key) {
    checkLocation(bucket, key);
    const { data, error } = await supabaseAdmin().storage.from(bucket).download(key);
    if (error || !data) return null;
    return { bytes: new Uint8Array(await data.arrayBuffer()), contentType: data.type };
  },
  async signedUrl(bucket, key, downloadName, ttlSeconds = SIGNED_URL_TTL_SECONDS) {
    checkLocation(bucket, key);
    const { data, error } = await supabaseAdmin()
      .storage.from(bucket)
      .createSignedUrl(key, ttlSeconds, { download: downloadName });
    if (error || !data) throw new Error(`Storage: ${error?.message ?? 'no signed URL'}`);
    return data.signedUrl;
  },
  async remove(bucket, key) {
    checkLocation(bucket, key);
    await supabaseAdmin().storage.from(bucket).remove([key]);
  },
};

const disk = diskStorage();

/** The active backend: Supabase when configured, disk with KH_DATA=postgres, else memory. */
export const fileStorage = (): FileStorage =>
  isSupabaseConfigured() ? supabaseStorage : isPostgresEnabled() ? disk : memoryStorage;

/** Response headers for streaming a stored file through an authorised route. */
export const downloadHeaders = (name: string, contentType: string, inline = false) => ({
  'content-type': contentType,
  'content-disposition': contentDisposition(name, inline),
  'cache-control': 'private, no-store',
  'x-content-type-options': 'nosniff',
  'content-security-policy': "default-src 'none'; sandbox",
});
